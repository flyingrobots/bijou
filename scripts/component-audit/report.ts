import type { Finding } from './checks.js';
import type { Rendered } from './render.js';

export interface Audited {
  readonly rendered: Rendered;
  readonly findings: readonly Finding[];
}

/** A stable id for a combination, used in reports and the error baseline. */
export function comboId(r: Rendered): string {
  const { story, variantIndex, mode, theme, scheme } = r.combo;
  const variant = story.variants[variantIndex]?.id ?? String(variantIndex);
  const colour = mode === 'interactive' || mode === 'static' ? ` ${theme}-${scheme}` : '';
  return `${story.id}/${variant} ${mode}${colour}`;
}

/** The baseline key for one error: the combination and the rule it broke. */
export const errorKey = (a: Audited, f: Finding): string => `${comboId(a.rendered)} ${f.rule}`;

/** A, B, or F: no findings, warnings only, or at least one error. */
export function grade(findings: readonly Finding[]): 'A' | 'B' | 'F' {
  if (findings.some((f) => f.severity === 'error')) return 'F';
  return findings.length > 0 ? 'B' : 'A';
}

const bullet = (f: Finding): string => `- **${f.severity.toUpperCase()}** \`${f.rule}\`: ${f.message}`;

/** (3) The report card for one combination. */
export function reportCard(a: Audited): string {
  const { combo, raw, surface } = a.rendered;
  const variant = combo.story.variants[combo.variantIndex];
  const lines = [
    `## ${combo.story.title}: ${variant?.label ?? '?'}`,
    '',
    `- Component: \`${combo.story.id}\` (${combo.story.family})`,
    `- Variant: \`${variant?.id ?? '?'}\``,
    `- Mode: \`${combo.mode}\``,
    ...(combo.mode === 'interactive' || combo.mode === 'static' ? [`- Theme: \`${combo.theme}\`, ${combo.scheme}`] : []),
    `- Output: ${raw === undefined ? 'surface' : 'string'}, ${String(surface?.width ?? 0)}×${String(surface?.height ?? 0)} cells`,
    `- Grade: **${grade(a.findings)}**`,
    '',
    ...(a.findings.length === 0 ? ['No findings.'] : a.findings.map(bullet)),
  ];
  return lines.join('\n');
}

/** The whole-matrix report: totals, every error, every warning, then a grade per component. */
export function matrixReport(all: readonly Audited[], newErrors: ReadonlySet<string>): string {
  const errors = all.flatMap((a) => a.findings.filter((f) => f.severity === 'error').map((f) => ({ a, f })));
  const warnings = all.flatMap((a) => a.findings.filter((f) => f.severity === 'warning').map((f) => ({ a, f })));
  const stories = [...new Set(all.map((a) => a.rendered.combo.story))];
  const row = (s: (typeof stories)[number]): string => {
    const mine = all.filter((a) => a.rendered.combo.story === s);
    const count = (sev: string): number => mine.reduce((n, a) => n + a.findings.filter((f) => f.severity === sev).length, 0);
    return `| \`${s.id}\` | ${s.family} | ${String(mine.length)} | ${String(count('error'))} | ${String(count('warning'))} | ${grade(mine.flatMap((a) => a.findings))} |`;
  };
  return [
    '# Component audit',
    '',
    'Every component variant rendered in each output mode, in every shell theme for `interactive` and `static`.',
    'Checks: output fits its mode; text contrast (WCAG 2: errors below 3:1, warnings below 4.5:1, dim text measured',
    'as drawn); every colour comes from the theme. Generated by `npm run audit:components -- --all`.',
    '',
    `- Combinations: ${String(all.length)}`,
    `- Errors: ${String(errors.length)} (${String(newErrors.size)} not in the baseline)`,
    `- Warnings: ${String(warnings.length)}`,
    '',
    '## ERRORS',
    '',
    ...(errors.length === 0 ? ['None.'] : errors.map(({ a, f }) => `- ${newErrors.has(errorKey(a, f)) ? '**NEW** ' : ''}\`${comboId(a.rendered)}\` \`${f.rule}\`: ${f.message}`)),
    '',
    '## WARNINGS',
    '',
    ...(warnings.length === 0 ? ['None.'] : warnings.map(({ a, f }) => `- \`${comboId(a.rendered)}\` \`${f.rule}\`: ${f.message}`)),
    '',
    '## Components',
    '',
    '| Component | Family | Combinations | Errors | Warnings | Grade |',
    '| --- | --- | --- | --- | --- | --- |',
    ...stories.map(row),
    '',
  ].join('\n');
}
