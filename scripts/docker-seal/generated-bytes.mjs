import { readdirSync, lstatSync } from 'node:fs';
import { join } from 'node:path';

/**
 * Sum the bytes the workload wrote under `roots` since `baseline` was recorded.
 * With `record`, store every file's current size in `baseline` instead.
 * Git object directories are bounded data, not logs, and are not walked.
 */
export function generatedBytes(roots, baseline, record = false, files = { readdirSync, lstatSync }) {
  let total = 0;
  function visit(path) {
    for (const name of files.readdirSync(path)) {
      const file = join(path, name); let s;
      try { s = files.lstatSync(file); } catch (error) { if (error.code === 'ENOENT') continue; throw error; }
      if (s.isDirectory()) {
        // Git objects are bounded data, not logs. All other generated bytes
        // conservatively consume the log allowance regardless of filename.
        if (!file.includes('/.git/objects')) visit(file);
      } else if (s.isFile()) {
        if (record) baseline.set(file, s.size);
        else total += Math.max(0, s.size - (baseline.get(file) ?? 0));
      }
    }
  }
  for (const root of roots) visit(root);
  return total;
}
