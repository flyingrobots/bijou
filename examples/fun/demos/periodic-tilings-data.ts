function decode([name, packed]: readonly [string, string]): TilingRecord {
  const values = Array.from(packed, (c) => c.charCodeAt(0) - 76);
  const quads = Array.from({ length: Math.floor(values.length / 4) }, (_, i) => values.slice(i * 4, i * 4 + 4));
  return { name, t1: quads[0] ?? [1, 0, 0, 0], t2: quads[1] ?? [0, 0, 0, 1], seeds: quads.slice(2) };
}

