// Each entry packs the notebook's integer vectors in the basis w^0..w^3 (unit vectors at 0, 30, 60 and 90 degrees):
// T1, then T2, then every seed, four components each, one letter per component (code - 76, so 'L' is 0).

/** A tiling as the notebook stores it: two translation vectors and the seed vertices of the main tile, in the w basis. */
export interface TilingRecord {
  readonly name: string;
  readonly t1: readonly number[];
  readonly t2: readonly number[];
  readonly seeds: readonly (readonly number[])[];
}

/** One database of the notebook: its name and its patterns. */
export interface TilingDatabase {
  readonly name: string;
  readonly patterns: readonly TilingRecord[];
}

